CREATE TABLE render_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  edit_id BIGINT UNSIGNED NOT NULL,
  draft_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  status ENUM('queued','processing','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
  progress INT UNSIGNED NOT NULL DEFAULT 0,
  attempt INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 3,
  configuration_version INT UNSIGNED NOT NULL,
  error_code VARCHAR(64) NULL,
  error_message TEXT NULL,
  payload_json JSON NOT NULL,
  result_json JSON NULL,
  bullmq_job_id VARCHAR(255) NULL,
  processing_job_id BIGINT UNSIGNED NULL,
  cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
  started_at TIMESTAMP NULL,
  completed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_render_jobs_edit (edit_id, id),
  KEY idx_render_jobs_user (user_id, created_at),
  CONSTRAINT fk_render_jobs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_render_jobs_edit FOREIGN KEY (edit_id) REFERENCES clip_edits (id) ON DELETE CASCADE,
  CONSTRAINT fk_render_jobs_draft FOREIGN KEY (draft_id) REFERENCES shorts_drafts (id) ON DELETE CASCADE,
  CONSTRAINT fk_render_jobs_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_render_jobs_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE rendered_videos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  render_job_id BIGINT UNSIGNED NOT NULL,
  edit_id BIGINT UNSIGNED NOT NULL,
  draft_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  storage_key VARCHAR(255) NOT NULL,
  thumbnail_key VARCHAR(255) NULL,
  container VARCHAR(16) NOT NULL DEFAULT 'mp4',
  video_codec VARCHAR(32) NOT NULL DEFAULT 'h264',
  audio_codec VARCHAR(32) NOT NULL DEFAULT 'aac',
  width INT UNSIGNED NOT NULL,
  height INT UNSIGNED NOT NULL,
  duration_ms INT UNSIGNED NOT NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  configuration_version INT UNSIGNED NOT NULL,
  quality_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rendered_videos_job (render_job_id),
  KEY idx_rendered_videos_edit (edit_id, id),
  CONSTRAINT fk_rendered_videos_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_rendered_videos_job FOREIGN KEY (render_job_id) REFERENCES render_jobs (id) ON DELETE CASCADE,
  CONSTRAINT fk_rendered_videos_edit FOREIGN KEY (edit_id) REFERENCES clip_edits (id) ON DELETE CASCADE,
  CONSTRAINT fk_rendered_videos_draft FOREIGN KEY (draft_id) REFERENCES shorts_drafts (id) ON DELETE CASCADE,
  CONSTRAINT fk_rendered_videos_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_rendered_videos_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
