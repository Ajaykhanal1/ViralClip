CREATE TABLE clip_analyses (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  processing_job_id BIGINT UNSIGNED NULL,
  analysis_key VARCHAR(64) NOT NULL,
  model VARCHAR(64) NOT NULL,
  source_duration_ms INT UNSIGNED NOT NULL,
  candidates_generated INT UNSIGNED NOT NULL DEFAULT 0,
  overlapping_skipped INT UNSIGNED NOT NULL DEFAULT 0,
  duplicate_skipped INT UNSIGNED NOT NULL DEFAULT 0,
  weights_json JSON NOT NULL,
  disclaimer VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_clip_analyses_key (analysis_key),
  KEY idx_clip_analyses_source_created (source_video_id, created_at),
  KEY idx_clip_analyses_user_created (user_id, created_at),
  CONSTRAINT fk_clip_analyses_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_analyses_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_analyses_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_analyses_job FOREIGN KEY (processing_job_id) REFERENCES processing_jobs (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE clip_recommendations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  analysis_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  candidate_id VARCHAR(64) NOT NULL,
  start_ms INT UNSIGNED NOT NULL,
  end_ms INT UNSIGNED NOT NULL,
  duration_ms INT UNSIGNED NOT NULL,
  hook_ms INT UNSIGNED NOT NULL,
  transcript TEXT NOT NULL,
  suggested_title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  engagement_score DECIMAL(5,2) NOT NULL,
  explanation TEXT NOT NULL,
  signals_json JSON NOT NULL,
  subtitle_config_json JSON NOT NULL,
  status ENUM('suggested', 'selected', 'rejected') NOT NULL DEFAULT 'suggested',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_clip_recommendations_analysis (analysis_id),
  KEY idx_clip_recommendations_source_status (source_video_id, status, engagement_score),
  KEY idx_clip_recommendations_user_created (user_id, created_at),
  CONSTRAINT fk_clip_recommendations_analysis FOREIGN KEY (analysis_id) REFERENCES clip_analyses (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_recommendations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_recommendations_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_clip_recommendations_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE,
  CONSTRAINT chk_clip_recommendations_time CHECK (end_ms > start_ms AND hook_ms >= start_ms AND hook_ms <= end_ms),
  CONSTRAINT chk_clip_recommendations_score CHECK (engagement_score >= 0 AND engagement_score <= 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
