CREATE TABLE content_rights (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NULL,
  subject_type ENUM('source_video', 'music', 'audio_asset', 'other') NOT NULL DEFAULT 'source_video',
  subject_label VARCHAR(255) NOT NULL,
  ownership_type ENUM('original', 'licensed', 'public_domain', 'unknown') NOT NULL,
  status ENUM('declared', 'pending_review', 'verified', 'rejected', 'expired') NOT NULL DEFAULT 'declared',
  commercial_use TINYINT(1) NOT NULL DEFAULT 0,
  derivative_work TINYINT(1) NOT NULL DEFAULT 0,
  youtube_publication TINYINT(1) NOT NULL DEFAULT 0,
  music_rights_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  user_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  confirmed_at TIMESTAMP NULL DEFAULT NULL,
  permission_details TEXT NULL,
  notes TEXT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  updated_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_content_rights_user_project (user_id, project_id, created_at),
  KEY idx_content_rights_source (source_video_id),
  KEY idx_content_rights_status (status),
  CONSTRAINT fk_content_rights_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_content_rights_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_content_rights_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE SET NULL,
  CONSTRAINT fk_content_rights_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_content_rights_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE content_licenses (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  content_rights_id BIGINT UNSIGNED NOT NULL,
  license_type VARCHAR(120) NOT NULL,
  licensor VARCHAR(255) NULL,
  license_reference VARCHAR(255) NULL,
  permission_details TEXT NULL,
  starts_at DATE NULL,
  expires_at DATE NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_content_licenses_rights (content_rights_id),
  KEY idx_content_licenses_expires (expires_at),
  CONSTRAINT fk_content_licenses_rights FOREIGN KEY (content_rights_id) REFERENCES content_rights (id) ON DELETE CASCADE,
  CONSTRAINT fk_content_licenses_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE rights_documents (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  content_rights_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  storage_key VARCHAR(512) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NULL,
  size_bytes BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rights_documents_storage_key (storage_key),
  KEY idx_rights_documents_rights (content_rights_id),
  CONSTRAINT fk_rights_documents_rights FOREIGN KEY (content_rights_id) REFERENCES content_rights (id) ON DELETE CASCADE,
  CONSTRAINT fk_rights_documents_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_rights_documents_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE copyright_checks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NULL,
  context ENUM('publish', 'render', 'upload_youtube', 'manual') NOT NULL,
  result ENUM('pass', 'blocked') NOT NULL,
  reasons_json JSON NULL,
  checked_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_copyright_checks_project (project_id, created_at),
  KEY idx_copyright_checks_source (source_video_id, created_at),
  CONSTRAINT fk_copyright_checks_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_copyright_checks_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_copyright_checks_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE SET NULL,
  CONSTRAINT fk_copyright_checks_checked_by FOREIGN KEY (checked_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

