CREATE TABLE shorts_drafts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  recommendation_id BIGINT UNSIGNED NULL,
  analysis_id BIGINT UNSIGNED NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('queued','processing','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
  selected TINYINT(1) NOT NULL DEFAULT 0,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  start_ms INT UNSIGNED NOT NULL,
  end_ms INT UNSIGNED NOT NULL,
  hook_ms INT UNSIGNED NOT NULL,
  duration_ms INT UNSIGNED NOT NULL,
  width INT UNSIGNED NOT NULL DEFAULT 1080,
  height INT UNSIGNED NOT NULL DEFAULT 1920,
  framing ENUM('smart','center','face','speaker') NOT NULL DEFAULT 'smart',
  crop_x DECIMAL(5,3) NOT NULL DEFAULT 0,
  crop_y DECIMAL(5,3) NOT NULL DEFAULT 0,
  subtitle_config_json JSON NULL,
  audio_config_json JSON NOT NULL,
  intro_json JSON NOT NULL,
  outro_json JSON NOT NULL,
  edit_data_json JSON NOT NULL,
  storage_key VARCHAR(255) NULL,
  thumbnail_key VARCHAR(255) NULL,
  error_message TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_shorts_drafts_version (recommendation_id, version),
  KEY idx_shorts_drafts_source (source_video_id, id),
  KEY idx_shorts_drafts_user (user_id, created_at),
  CONSTRAINT fk_shorts_drafts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_shorts_drafts_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_shorts_drafts_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE,
  CONSTRAINT fk_shorts_drafts_recommendation FOREIGN KEY (recommendation_id) REFERENCES clip_recommendations (id) ON DELETE CASCADE,
  CONSTRAINT fk_shorts_drafts_analysis FOREIGN KEY (analysis_id) REFERENCES clip_analyses (id) ON DELETE SET NULL,
  CONSTRAINT chk_shorts_drafts_time CHECK (end_ms > start_ms AND hook_ms >= start_ms AND hook_ms <= end_ms),
  CONSTRAINT chk_shorts_drafts_crop CHECK (crop_x >= -1 AND crop_x <= 1 AND crop_y >= -1 AND crop_y <= 1),
  CONSTRAINT chk_shorts_drafts_dims CHECK (width > 0 AND height > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
