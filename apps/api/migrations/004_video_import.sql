CREATE TABLE upload_sessions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NULL,
  declared_size_bytes BIGINT UNSIGNED NULL,
  status ENUM('pending', 'uploading', 'uploaded', 'failed', 'canceled', 'expired') NOT NULL DEFAULT 'pending',
  storage_key VARCHAR(512) NULL,
  upload_token_hash CHAR(64) NULL,
  bytes_received BIGINT UNSIGNED NOT NULL DEFAULT 0,
  error_message VARCHAR(255) NULL,
  expires_at TIMESTAMP NOT NULL,
  completed_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_upload_sessions_user_status (user_id, status, created_at),
  KEY idx_upload_sessions_project (project_id),
  KEY idx_upload_sessions_expires (status, expires_at),
  UNIQUE KEY uq_upload_sessions_storage_key (storage_key),
  CONSTRAINT fk_upload_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_upload_sessions_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE source_videos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_type ENUM('upload', 'youtube') NOT NULL,
  status ENUM('pending', 'awaiting_authorized_source', 'ready', 'failed') NOT NULL DEFAULT 'pending',
  title VARCHAR(255) NOT NULL,
  original_filename VARCHAR(255) NULL,
  source_url VARCHAR(512) NULL,
  youtube_video_id VARCHAR(32) NULL,
  thumbnail_url VARCHAR(512) NULL,
  metadata_json JSON NULL,
  error_message VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_source_videos_project_created (project_id, created_at),
  KEY idx_source_videos_user_created (user_id, created_at),
  KEY idx_source_videos_youtube (youtube_video_id),
  CONSTRAINT fk_source_videos_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_source_videos_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE media_assets (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  kind ENUM('original', 'authorized_source') NOT NULL,
  storage_key VARCHAR(512) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NULL,
  size_bytes BIGINT UNSIGNED NULL,
  duration_seconds DECIMAL(12, 3) NULL,
  width INT UNSIGNED NULL,
  height INT UNSIGNED NULL,
  frame_rate DECIMAL(10, 4) NULL,
  video_codec VARCHAR(64) NULL,
  audio_codec VARCHAR(64) NULL,
  audio_channels INT UNSIGNED NULL,
  audio_sample_rate INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_media_assets_storage_key (storage_key),
  KEY idx_media_assets_source (source_video_id),
  KEY idx_media_assets_user (user_id, created_at),
  CONSTRAINT fk_media_assets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_media_assets_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
