CREATE TABLE youtube_accounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  channel_id VARCHAR(128) NOT NULL,
  channel_title VARCHAR(255) NOT NULL,
  channel_handle VARCHAR(255) NULL,
  thumbnail_url VARCHAR(512) NULL,
  scopes_json JSON NOT NULL,
  access_token_enc TEXT NOT NULL,
  refresh_token_enc TEXT NOT NULL,
  token_expires_at TIMESTAMP NULL,
  status ENUM('connected','disconnected','revoked','expired') NOT NULL DEFAULT 'connected',
  connected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_youtube_accounts_user (user_id),
  CONSTRAINT fk_youtube_accounts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE youtube_uploads (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  youtube_account_id BIGINT UNSIGNED NOT NULL,
  rendered_video_id BIGINT UNSIGNED NOT NULL,
  processing_job_id BIGINT UNSIGNED NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  source_video_id BIGINT UNSIGNED NOT NULL,
  draft_id BIGINT UNSIGNED NOT NULL,
  status ENUM('queued','uploading','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
  progress INT UNSIGNED NOT NULL DEFAULT 0,
  title VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  tags_json JSON NOT NULL,
  visibility ENUM('public','private','unlisted') NOT NULL,
  rights_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  rights_check_json JSON NULL,
  video_id VARCHAR(64) NULL,
  video_url VARCHAR(512) NULL,
  error_code VARCHAR(64) NULL,
  error_message TEXT NULL,
  attempt INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 3,
  started_at TIMESTAMP NULL,
  completed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_youtube_uploads_user (user_id, created_at),
  KEY idx_youtube_uploads_video (rendered_video_id, id),
  CONSTRAINT fk_youtube_uploads_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_youtube_uploads_account FOREIGN KEY (youtube_account_id) REFERENCES youtube_accounts (id) ON DELETE CASCADE,
  CONSTRAINT fk_youtube_uploads_video FOREIGN KEY (rendered_video_id) REFERENCES rendered_videos (id) ON DELETE CASCADE,
  CONSTRAINT fk_youtube_uploads_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_youtube_uploads_source FOREIGN KEY (source_video_id) REFERENCES source_videos (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
